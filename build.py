# Builds app/engine.js from the bot's own templates + analyzer, so the app and the bot draw identically.
import re, pathlib
R = pathlib.Path(__file__).resolve().parent.parent
def body(html):
    s = re.search(r'<script>(.*?)</script>', (R/'templates'/html).read_text(), re.S).group(1)
    s = s.strip()
    s = re.sub(r'^/\*.*?\*/\s*', '', s, flags=re.S)
    assert s.startswith('(function () {') and s.endswith('})();'), html
    s = s[len('(function () {'):-len('})();')]
    s = s.replace("const cv = document.getElementById('c'), g = cv.getContext('2d');", "const g = cv.getContext('2d');")
    s = s.replace('window.', 'api.')
    return s
an = (R/'lib'/'analyze.mjs').read_text()
an = an[an.index('function fft'):].replace('export function analyze', 'function analyze')
out = f"""// Grokly engine (generated by build.py from templates/*.html + lib/analyze.mjs — edit those, then rebuild)
(function () {{
const SR = 44100;
{an}
function makeWave(cv) {{ const api = {{}};
{body('wave.html')}
return api; }}
function makeCards(cv) {{ const api = {{}};
{body('cards.html')}
return api; }}
window.GroklyEngine = {{ SR, analyze, makeWave, makeCards }};
}})();
"""
(R/'app'/'engine.js').write_text(out)
print('engine.js', len(out))
